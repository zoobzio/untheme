import type { OutputFile } from "./types";

/**
 * Makes pretty JSON. The JSON is also a valid JavaScript expression, and an
 * emitted module exports it as a literal.
 */
export const json = (value: unknown): string => {
  return JSON.stringify(value, null, 2);
};

/** The banner at the top of every emitted module. It names the theme of the module. */
export const banner = (id: string): string => {
  return `// Generated by @untheme/kit from ${JSON.stringify(id)}. Do not edit by hand.`;
};

/** A string-literal union with one member per line, or `never` when empty. It follows a bare `=`. */
export const union = (members: string[]): string => {
  if (members.length === 0) {
    return " never";
  }
  return members.map((member) => `\n  | ${JSON.stringify(member)}`).join("");
};

/**
 * Makes a module and its declarations as two files. TypeScript pairs a `.d.mts`
 * file with an `.mjs` file under every module resolution. This includes a
 * relative `import "./untheme/config.mjs"` in an app.
 *
 * @param name - The name of the module, with no extension.
 * @param mjs - The source lines of the module.
 * @param dts - The source lines of the declaration.
 */
export const pair = (
  name: string,
  mjs: string[],
  dts: string[],
): OutputFile[] => {
  return [
    { path: `${name}.mjs`, contents: `${mjs.join("\n")}\n` },
    { path: `${name}.d.mts`, contents: `${dts.join("\n")}\n` },
  ];
};
