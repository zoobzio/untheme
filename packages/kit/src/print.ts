import type { OutputFile } from "./types";

/**
 * Pretty JSON — also a valid JavaScript expression, so it doubles as the
 * literal an emitted module exports.
 */
export const json = (value: unknown): string => {
  return JSON.stringify(value, null, 2);
};

/** The banner atop every emitted module, naming the theme it was built from. */
export const banner = (id: string): string => {
  return `// Generated by @untheme/kit from ${JSON.stringify(id)}. Do not edit by hand.`;
};

/** A string-literal union, one member per line; `never` when empty. Follows a bare `=`. */
export const union = (members: string[]): string => {
  if (members.length === 0) {
    return " never";
  }
  return members.map((member) => `\n  | ${JSON.stringify(member)}`).join("");
};

/**
 * A module and its declarations, emitted side by side. `.d.mts` is what
 * TypeScript pairs with an `.mjs` under every module resolution, including a
 * relative `import "./untheme/config.mjs"` in an app.
 *
 * @param name - The module's name, without an extension.
 * @param mjs - The module's source lines.
 * @param dts - The declaration's source lines.
 */
export const pair = (
  name: string,
  mjs: string[],
  dts: string[],
): OutputFile[] => {
  return [
    { path: `${name}.mjs`, contents: `${mjs.join("\n")}\n` },
    { path: `${name}.d.mts`, contents: `${dts.join("\n")}\n` },
  ];
};
